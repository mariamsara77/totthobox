                        const hls = new Hls({
                            maxBufferLength: 8,
                            maxMaxBufferLength: 20,
                            liveSyncDurationCount: 2,
                            liveMaxLatencyDurationCount: 5,
                            enableWorker: true,
                            lowLatencyMode: true,
                            enableSoftwareAES: true,
                            xhrSetup: (xhr) => {
                                xhr.timeout = 10000;
                            },
                        });

