        function modernDrawingApp() {
            return {
                canvas: null,
                ctx: null,
                isDrawing: false,
                lastX: 0,
                lastY: 0,

                currentColor: '#000000',
                currentSize: 5,
                opacity: 1,
                activeTool: 'pen',

                guideText: '',
                currentPaperStyle: 'blank',
                fileName: `Totthobox-writing-practice-${new Date().toISOString().slice(0, 10)}`,
                saveFormat: 'png',
                transparentBackground: false,

                pressureSensitivity: false,
                smoothing: true,
                guideLines: true,

                drawingHistory: [],
                historyIndex: -1,

                colorPresets: ['#000000', '#dc2626', '#2563eb', '#16a34a', '#ea580c', '#9333ea', '#64748b', '#ffffff'],

                tools: [{
                        id: 'pen',
                        name: 'Pen'
                    },
                    {
                        id: 'eraser',
                        name: 'Eraser'
                    }
                ],

                paperStyles: [{
                        id: 'blank',
                        name: 'Blank',
                        class: 'bg-white'
                    },
                    {
                        id: 'lined',
                        name: 'Lined',
                        class: 'bg-white bg-lined-paper'
                    },
                    {
                        id: 'grid',
                        name: 'Grid',
                        class: 'bg-white bg-grid-paper'
                    },
                    {
                        id: 'graph',
                        name: 'Graph',
                        class: 'bg-white bg-graph-paper'
                    },
                    {
                        id: 'yellow',
                        name: 'Yellow',
                        class: 'bg-yellow-50'
                    },
                    {
                        id: 'parchment',
                        name: 'Parchment',
                        class: 'bg-amber-50'
                    }
                ],

                characterCategories: [{
                        name: 'English Uppercase',
                        open: false,
                        characters: 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')
                    },
                    {
                        name: 'English Lowercase',
                        open: false,
                        characters: 'abcdefghijklmnopqrstuvwxyz'.split('')
                    },
                    {
                        name: 'Numbers',
                        open: false,
                        characters: '0123456789'.split('')
                    },
                    {
                        name: 'Bangla Vowels (স্বরবর্ণ)',
                        open: false,
                        characters: 'অআইঈউঊঋএঐওঔ'.split('')
                    },
                    {
                        name: 'Bangla Consonants (ব্যঞ্জনবর্ণ)',
                        open: false,
                        characters: 'কখগঘঙচছজঝঞটঠডঢণতথদধনপফবভমযরলশষসহড়ঢ়য়'.split('')
                    },
